-- | A Template-Haskell realisation of the surface syntax described in
-- @jfp/sections/prototype.tex@, subsection "Effect Handler Interface"
-- (\label{sec:interface}, roughly lines 317-387), i.e.
--
-- > [effect| data NDet = NDet { decide :: Op () Bool } |]
-- >
-- > pgm =
-- >   handlerRet (\x -> return [x])
-- >              (NDet { decide = operation (\x l k -> (+) <$> k True <*> k False) }) $
-- >   do y <- perform decide (); return (not y)
--
-- This module defines the @effect@ quasiquoter plus the runtime
-- combinators ('operation', 'perform', 'handlerRet', 'handler',
-- 'runSel') it builds on, all layered on top of the existing,
-- untouched 'SelectionMonad_ParameterSupport2' primitives ('op', 'opS',
-- 'Handler', 'handle', ':?', ':*', 'run', ...).
--
-- GHC's TH staging restriction means the quasiquoter must live in a
-- different module from any use of @[effect| ... |]@; see
-- @Section4Example.hs@ for the worked NDet/decide example and the
-- Max/password example from @jfp/sections/examples.lhs@.
--
-- =====================================================================
-- DESIGN NOTE -- the one deliberate deviation from the paper's literal
-- surface syntax, and why it is forced rather than a convenience choice
-- =====================================================================
--
-- The paper writes the handler definition using ordinary-looking GHC
-- record syntax, reusing the effect's own name as both the type and the
-- "operation" field name:
--
-- >   NDet { decide = operation (\x l k -> e) }
--
-- together with, in the very same program, a *plain function call*
--
-- >   perform decide ()
--
-- For both to typecheck as written, "decide" would have to be
-- simultaneously (a) an ordinary top-level function
-- @() -> Sel r e Bool@ (needed so @perform decide ()@ performs the
-- operation -- this is the reading strongly supported by the ground
-- truth hand-written Opt\/LR desugaring in
-- @SelectionMonad_ParameterSupport2.hs@'s commented-out linear
-- regression example, where @optimize@\/@lrate@ are exactly such plain
-- functions), and (b) a record field selector of some handler-definition
-- type, generated by the *same* field name "decide" so that
-- @NDet { decide = ... }@ parses as real record construction.
--
-- These two roles need genuinely different types: (a) needs
-- @I -> Sel r e O@, while (b)'s field, holding the *algebra clause* for
-- *all* possible inputs, needs
-- @I -> (O -> Sel r e r) -> (O -> Sel r e b) -> Sel r e b@ (the clause
-- type 'operation' expects) -- a shape with no fixed "b" at all, since
-- the dispatch functor used by 'op' is handler-agnostic. A single GHC
-- record field cannot have two different types depending on which
-- expression it appears in, and two top-level bindings cannot share one
-- name in one module (GHC's @NoFieldSelectors@, which could resolve
-- this, is a 9.2+ extension -- unavailable under the pinned GHC 8.10.2).
-- So literal record syntax for the handler definition is not
-- achievable here.
--
-- The deviation adopted: the handler-definition value is built by
-- applying the generated constructor *positionally* instead of via
-- record syntax, i.e.
--
-- >   NDet (operation (\x l k -> e))
--
-- instead of @NDet { decide = operation (\x l k -> e) }@. This keeps
-- 'operation', 'perform', 'handlerRet', 'handler', 'runSel' and the
-- per-field function names (e.g. @decide@) *exactly* as the paper
-- writes them -- only the handler-definition literal's braces/field
-- label are dropped, which generalises uniformly to multi-operation
-- effects (one positional argument per declared field, in declaration
-- order) with no further special-casing. Every other part of the
-- worked example is verbatim.
module EffectTH
  ( effect,
    operation,
    perform,
    ToAlgebra (..),
    handlerRet,
    handler,
    runSel,
  )
where

import Data.Char (isAlphaNum, isSpace, isUpper)
import Data.List (nub)
import Language.Haskell.TH
import Language.Haskell.TH.Quote
import SelectionMonad_ParameterSupport2

-- ---------------------------------------------------------------------
-- Runtime combinators
-- ---------------------------------------------------------------------

-- | @operation (\x l k -> e)@: @x@ is the operation argument, @l@ the
-- choice (loss) continuation, @k@ the delimited (resume) continuation
-- (prototype.tex, sec:interface). This is purely a readability
-- combinator fixing the clause's type -- it does no work of its own.
operation ::
  (i -> (o -> Sel r e r) -> (o -> Sel r e b) -> Sel r e b) ->
  (i -> (o -> Sel r e r) -> (o -> Sel r e b) -> Sel r e b)
operation = id

-- | @perform f x = f x@: the per-field function generated by
-- @[effect| ... |]@ (e.g. @decide@, @optimize@, @lrate@) already takes
-- its operation argument directly -- cf. @optimize lst = op (Opt lst
-- pure)@ in @SelectionMonad_ParameterSupport2.hs@'s commented Opt\/LR
-- example, called there with no wrapper at all. @perform@ exists only
-- so programs can be written exactly as the paper shows them.
perform :: (i -> Sel r e o) -> i -> Sel r e o
perform f x = f x

-- | Connects a handler-definition value (e.g. @NDet@, generated by
-- @[effect| ... |]@) to the raw algebra 'handle' dispatches on, built
-- from the matching dispatch functor (e.g. @NDet_F@).
class ToAlgebra h f | h -> f where
  toAlgebra :: h r e b -> f (Sel r e r, Sel r e b) -> Sel r e b

-- | @handlerRet@: a return clause, a handler definition, and the
-- computation to be handled. The handler parameter @p@ (cf.
-- 'handleP'\/'Handler' in @SelectionMonad_ParameterSupport2.hs@) is
-- fixed internally to @()@: 'handlerRet'\/'handler' are the
-- NON-parameterized entry points the paper describes (as opposed to a
-- @handlerPRet@\/@handlerP@-style parameterized variant, which would
-- thread a real @p@ through instead of @()@ -- not needed by any
-- worked example here, so not built).
handlerRet ::
  (ToAlgebra h f, Functor f, Functor e, Monoid r) =>
  (a -> Sel r e b) ->
  h r e b ->
  Sel r (f :* e) a ->
  Sel r e b
handlerRet ret h =
  handle
    Handler
      { hret = \_ a -> ret a,
        hops = \t p -> toAlgebra h (fmap (\(c1, c2) -> (c1 p, c2 p)) t)
      }
    ()

-- | @handler@: 'handlerRet' without an explicit return clause (defaults
-- to 'return'), matching the paper's "We can also use @handler@ without
-- a return clause."
handler ::
  (ToAlgebra h f, Functor f, Functor e, Monoid r) =>
  h r e a ->
  Sel r (f :* e) a ->
  Sel r e a
handler = handlerRet return

-- | @runSel@: run a closed program, discarding the recorded loss (the
-- paper's examples print only the result, e.g. @runSel pgm@ returns
-- @[False, True]@, not a @(result, loss)@ pair).
runSel :: (Monoid r) => Sel r VoidEff a -> a
runSel = fst . run

-- ---------------------------------------------------------------------
-- A tiny hand-rolled parser for the restricted grammar
--   data <ConName> = <ConName> { <field> :: Op <Type> <Type>, ... }
-- (haskell-src-meta is not installed, and none is needed: this is far
-- simpler than arbitrary Haskell).
-- ---------------------------------------------------------------------

-- | A restricted type grammar: identifiers (lowercase = type variable,
-- uppercase = type constructor, including "()"), type application,
-- lists, and tuples. Enough for every @Op I O@ actually seen (@()@,
-- @Bool@, @[a]@, @a@, @[Param]@, @[Float]@, @(Step,Step)@, ...), not
-- arbitrary Haskell types.
data PTy
  = TyVar String
  | TyCon String
  | TyApp PTy PTy
  | TyList PTy
  | TyTuple [PTy]
  deriving (Show)

freeVars :: PTy -> [String]
freeVars (TyVar v) = [v]
freeVars (TyCon _) = []
freeVars (TyApp a b) = freeVars a ++ freeVars b
freeVars (TyList a) = freeVars a
freeVars (TyTuple ts) = concatMap freeVars ts

type Field = (String, PTy, PTy)

data EffectDecl = EffectDecl {edName :: String, edFields :: [Field]}

type P a = String -> Either String (a, String)

skipWS :: String -> String
skipWS = dropWhile isSpace

lit :: String -> P ()
lit s inp =
  let inp' = skipWS inp
   in if take (length s) inp' == s
        then Right ((), drop (length s) inp')
        else Left ("expected " ++ show s ++ " near " ++ show (take 30 inp'))

ident :: P String
ident inp =
  let inp' = skipWS inp
      (tok, rest) = span (\c -> isAlphaNum c || c == '_' || c == '\'') inp'
   in if null tok
        then Left ("expected identifier near " ++ show (take 30 inp'))
        else Right (tok, rest)

-- | A single "atomic" type: identifier, unit, bracketed list, or
-- parenthesised type\/tuple.
parseAtom :: P PTy
parseAtom inp =
  let inp' = skipWS inp
   in case inp' of
        ('(' : rest) ->
          case skipWS rest of
            (')' : rest2) -> Right (TyCon "()", rest2)
            _ -> do
              (t1, r1) <- parseType rest
              goTuple [t1] r1
        ('[' : rest) -> do
          (t, r1) <- parseType rest
          case skipWS r1 of
            (']' : r2) -> Right (TyList t, r2)
            _ -> Left ("expected ']' near " ++ show (take 30 r1))
        _ -> do
          (name, r1) <- ident inp'
          Right (if isUpper (head name) then TyCon name else TyVar name, r1)
  where
    goTuple acc r =
      case skipWS r of
        (',' : r2) -> do (t, r3) <- parseType r2; goTuple (acc ++ [t]) r3
        (')' : r2) -> Right (if length acc == 1 then head acc else TyTuple acc, r2)
        _ -> Left ("expected ',' or ')' near " ++ show (take 30 r))

-- | A type-application chain of atoms (e.g. @Maybe Int@); greedily
-- consumes atoms until one fails to parse (i.e. until a terminator like
-- @,@, @)@, @]@, @}@ is hit).
parseType :: P PTy
parseType inp = do
  (a1, r1) <- parseAtom inp
  goApp a1 r1
  where
    goApp acc r =
      case parseAtom r of
        Right (a2, r2) -> goApp (TyApp acc a2) r2
        Left _ -> Right (acc, r)

parseField :: P Field
parseField inp = do
  (fname, r1) <- ident inp
  (_, r2) <- lit "::" r1
  (_, r3) <- lit "Op" r2
  (ity, r4) <- parseAtom r3
  (oty, r5) <- parseAtom r4
  Right ((fname, ity, oty), r5)

parseEffect :: P EffectDecl
parseEffect inp = do
  (_, r1) <- lit "data" inp
  (ename, r2) <- ident r1
  (_, r3) <- lit "=" r2
  (_cname, r4) <- ident r3 -- the constructor name; assumed == effect name, as in every example
  (_, r5) <- lit "{" r4
  (f1, r6) <- parseField r5
  (fs, r7) <- goFields [f1] r6
  (_, r8) <- lit "}" r7
  Right (EffectDecl ename fs, r8)
  where
    goFields acc r =
      case lit "," r of
        Right (_, r2) -> do (f, r3) <- parseField r2; goFields (acc ++ [f]) r3
        Left _ -> Right (acc, r)

runFullParse :: String -> Either String EffectDecl
runFullParse inp = do
  (decl, rest) <- parseEffect inp
  if all isSpace rest
    then Right decl
    else Left ("trailing input: " ++ show (take 40 rest))

-- ---------------------------------------------------------------------
-- Code generation: EffectDecl -> [Dec]
-- ---------------------------------------------------------------------

thType :: PTy -> Type
thType (TyCon "()") = TupleT 0
thType (TyCon c) = ConT (mkName c)
thType (TyVar v) = VarT (mkName v)
thType (TyApp f a) = AppT (thType f) (thType a)
thType (TyList a) = AppT ListT (thType a)
thType (TyTuple ts) = foldl AppT (TupleT (length ts)) (map thType ts)

-- | The dispatch-functor's constructor name for one field.
conFName :: String -> String -> Name
conFName eff fname = mkName (eff ++ "_F_" ++ fname)

functorName :: String -> Name
functorName eff = mkName (eff ++ "_F")

selT :: Type -> Type -> Type -> Type
selT r e a = AppT (AppT (AppT (ConT (mkName "Sel")) r) e) a

-- | @I -> (O -> Sel r e r) -> (O -> Sel r e b) -> Sel r e b@: the shape
-- 'operation' expects, and one positional field of the generated
-- handler-definition type.
clauseType :: Type -> Type -> Type -> Type -> Type -> Type
clauseType i o r e =
  let arr a b = AppT (AppT ArrowT a) b
   in \b ->
        arr
          i
          ( arr
              (arr o (selT r e r))
              (arr (arr o (selT r e b)) (selT r e b))
          )

genEffect :: EffectDecl -> Q [Dec]
genEffect (EffectDecl eff fields) = do
  let tyvarNames = nub (concatMap (\(_, i, o) -> freeVars i ++ freeVars o) fields)
      tyvars = map mkName tyvarNames
      effF = functorName eff
      rN = mkName "r"
      eN = mkName "e"
      bN = mkName "b"
      xN = mkName "x"
      -- The dispatch functor: data <eff>_F <tyvars> x
      --   = <eff>_F_<f1> I1 (O1 -> x) | ... deriving Functor
      functorCon (fname, ity, oty) =
        NormalC
          (conFName eff fname)
          [ (Bang NoSourceUnpackedness NoSourceStrictness, thType ity),
            (Bang NoSourceUnpackedness NoSourceStrictness, AppT (AppT ArrowT (thType oty)) (VarT xN))
          ]
      functorDecl =
        DataD
          []
          effF
          (map PlainTV (tyvars ++ [xN]))
          Nothing
          (map functorCon fields)
          [DerivClause Nothing [ConT ''Functor]]
      -- One perform-function per field: <fname> :: (Monoid r, Functor e,
      -- <eff>_F <tyvars> :? e) => I -> Sel r e O ; <fname> i = op (<Con> i pure)
      effFApplied = foldl AppT (ConT effF) (map VarT tyvars)
      performSig (fname, ity, oty) =
        SigD
          (mkName fname)
          ( ForallT
              (map PlainTV (tyvars ++ [rN, eN]))
              [ AppT (ConT ''Monoid) (VarT rN),
                AppT (ConT ''Functor) (VarT eN),
                AppT (AppT (ConT (mkName ":?")) effFApplied) (VarT eN)
              ]
              (AppT (AppT ArrowT (thType ity)) (selT (VarT rN) (VarT eN) (thType oty)))
          )
      performFun (fname, _, _) =
        FunD
          (mkName fname)
          [ Clause
              [VarP (mkName "i")]
              ( NormalB
                  ( AppE
                      (VarE (mkName "op"))
                      (AppE (AppE (ConE (conFName eff fname)) (VarE (mkName "i"))) (VarE 'pure))
                  )
              )
              []
          ]
      -- The handler-definition type: data <eff> <tyvars> r e b
      --   = <eff> (I1 -> (O1 -> Sel r e r) -> (O1 -> Sel r e b) -> Sel r e b) ...
      handlerCon =
        NormalC
          (mkName eff)
          [ (Bang NoSourceUnpackedness NoSourceStrictness, clauseType (thType ity) (thType oty) (VarT rN) (VarT eN) (VarT bN))
            | (_, ity, oty) <- fields
          ]
      handlerDecl =
        DataD [] (mkName eff) (map PlainTV (tyvars ++ [rN, eN, bN])) Nothing [handlerCon] []
      -- instance ToAlgebra (<eff> <tyvars>) (<eff>_F <tyvars>) where
      --   toAlgebra (<eff> f1 f2 ...) t = case t of
      --     <Con_k> i cont -> f_k i (\o -> fst (cont o)) (\o -> snd (cont o))
      fieldVars = [mkName ("f_" ++ show n) | (n, _) <- zip [(0 :: Int) ..] fields]
      tVar = mkName "t"
      oVar = mkName "o"
      iVar = mkName "i"
      contVar = mkName "cont"
      lamFstSnd sel = LamE [VarP oVar] (AppE (VarE sel) (AppE (VarE contVar) (VarE oVar)))
      matchFor fv (fname, _, _) =
        Match
          (ConP (conFName eff fname) [VarP iVar, VarP contVar])
          (NormalB (AppE (AppE (AppE (VarE fv) (VarE iVar)) (lamFstSnd 'fst)) (lamFstSnd 'snd)))
          []
      toAlgebraClause =
        Clause
          [ConP (mkName eff) (map VarP fieldVars), VarP tVar]
          (NormalB (CaseE (VarE tVar) (zipWith matchFor fieldVars fields)))
          []
      instDecl =
        InstanceD
          Nothing
          []
          ( AppT
              (AppT (ConT (mkName "ToAlgebra")) (foldl AppT (ConT (mkName eff)) (map VarT tyvars)))
              effFApplied
          )
          [FunD (mkName "toAlgebra") [toAlgebraClause]]
  pure $
    [functorDecl]
      ++ concatMap (\f -> [performSig f, performFun f]) fields
      ++ [handlerDecl, instDecl]

-- ---------------------------------------------------------------------
-- The quasiquoter itself
-- ---------------------------------------------------------------------

-- | @[effect| data NDet = NDet { decide :: Op () Bool } |]@: declares an
-- effect as described in prototype.tex, sec:interface. See the module
-- header for exactly what this generates and the one deliberate
-- deviation (positional handler-definition construction instead of
-- record syntax).
effect :: QuasiQuoter
effect =
  QuasiQuoter
    { quoteExp = err,
      quotePat = err,
      quoteType = err,
      quoteDec = \s -> case runFullParse s of
        Left e -> fail ("[effect| ... |]: parse error: " ++ e)
        Right decl -> genEffect decl
    }
  where
    err _ = fail "[effect| ... |] may only be used as a top-level declaration"
